int main(void) {
    configureFlash();

    // Turn on clock to GPIOB
    RCC->AHB2ENR |= (1 << 1);

    pitch();
    duration();

    // Set LED_PIN as output
    pinMode(LED_PIN, GPIO_OUTPUT);

   for(int i = 0; i < (sizeof(notes1)/sizeof(notes1[0])); i++) {
        // duration the note lasts
        runDuration(notes1[i][1]);
        while(!((TIM7->SR >> 0) & 1)){
          // pitch is on
          runPitch(notes1[i][0]);
          if (notes1[i][0] == 0){
            TIM6->SR &= ~(1 << 0); 
          }
          else {  
            while(!((TIM6->SR >> 0) & 1)){}         
              // note is running
              togglePin(LED_PIN);
              TIM6->SR &= ~(1 << 0);         
            }
          }
            
        TIM7->SR &= ~(1 << 0);
    }
    return 0;
}